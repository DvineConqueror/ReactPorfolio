async(page)=>{
const report=[];const check=(ok,label)=>{if(!ok)throw new Error(label);report.push(label);};
await page.route('https://challenges.cloudflare.com/**',route=>route.fulfill({contentType:'application/javascript',body:''}));
await page.addInitScript(()=>{window.turnstile={render:()=>'',remove:()=>{}};});
await page.emulateMedia({reducedMotion:'no-preference'});
await page.setViewportSize({width:1440,height:900});
await page.goto('http://127.0.0.1:8789/');
await page.locator('.portrait-atlas.is-active').waitFor();
const box=await page.locator('.hero-portrait').boundingBox(),cx=box.x+box.width/2,cy=box.y+box.height/2;
await page.mouse.move(cx-180,cy);
await page.waitForFunction(()=>document.querySelector('.hero-portrait').dataset.column==='0');
await page.evaluate(()=>{
window.__poseTrace=[0];
window.__poseObserver=new MutationObserver(()=>{const n=Number(document.querySelector('.hero-portrait').dataset.column);if(window.__poseTrace.at(-1)!==n)window.__poseTrace.push(n);});
window.__poseObserver.observe(document.querySelector('.hero-portrait'),{attributes:true,attributeFilter:['data-column']});
});
await page.mouse.move(cx+180,cy);
await page.waitForFunction(()=>document.querySelector('.hero-portrait').dataset.column==='5');
const trace=await page.evaluate(()=>{window.__poseObserver.disconnect();return window.__poseTrace;});
check(new Set(trace).size===6,'left-to-right head turn visits all six intermediate angles');
check(trace.every((v,i)=>!i||Math.abs(v-trace[i-1])<=1),'head turns in small steps instead of snapping across directions');
check(await page.locator('.portrait-atlas').count()===1,'one opaque portrait frame, no blended photo layers');
check(await page.locator('.portrait-atlas').evaluate(el=>getComputedStyle(el).opacity==='1'&&getComputedStyle(el).transitionDuration==='0s'),'no photo crossfade or sprite sliding transition');
await page.mouse.move(cx-180,cy);
await page.waitForFunction(()=>{const col=Number(document.querySelector('.hero-portrait').dataset.column);return col>1&&col<4;});
const middle=Number(await page.locator('.hero-portrait').getAttribute('data-column'));
await page.mouse.move(cx+180,cy);
await page.waitForFunction(()=>document.querySelector('.hero-portrait').dataset.column==='5');
check(middle>0&&middle<5,'mid-turn cursor reversal retargets through current orientation');
await page.mouse.move(cx,cy-180);
await page.waitForFunction(()=>document.querySelector('.hero-portrait').dataset.row==='0');
await page.mouse.move(cx,cy+180);
await page.waitForFunction(()=>document.querySelector('.hero-portrait').dataset.row==='5');
check(true,'vertical head turns use intermediate pitch angles');
await page.mouse.move(cx-130,cy-130);
await page.waitForFunction(()=>document.querySelector('.hero-portrait').dataset.direction==='up-left');
await page.mouse.move(cx+130,cy+130);
await page.waitForFunction(()=>document.querySelector('.hero-portrait').dataset.direction==='down-right');
check(true,'diagonal head orientation follows cursor');
await page.mouse.move(cx+300,cy);
await page.waitForFunction(()=>document.querySelector('.hero-portrait').dataset.direction==='center');
await page.screenshot({path:'output/playwright/natural-portrait-desktop.png',animations:'disabled'});
check(true,'head returns to neutral outside nearby radius');
await page.emulateMedia({reducedMotion:'reduce'});
await page.waitForFunction(()=>!document.querySelector('.portrait-atlas'));
check(await page.locator('.portrait-original').evaluate(el=>getComputedStyle(el).opacity==='1'),'reduced-motion static original remains intact');
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'output/playwright/natural-portrait-mobile.png',animations:'disabled'});
check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'phone layout fits viewport');
const iconUrl=await page.locator('link[rel="icon"]').getAttribute('href');
const icon=await page.request.get('http://127.0.0.1:8789'+iconUrl);
check(icon.ok()&&iconUrl.includes('ha-2')&&(await icon.text()).includes('#0c0c0f'),'new cache-busted monochrome favicon loads');
const preview=await page.context().newPage();
await preview.setViewportSize({width:360,height:180});
await preview.setContent('<body style="margin:0;padding:24px;background:#e9e9e9;font:13px monospace;display:flex;align-items:center;gap:28px"><div><img src="http://127.0.0.1:8789/favicon.svg?v=ha-2" width="16" height="16"><p>16px</p></div><div><img src="http://127.0.0.1:8789/favicon.svg?v=ha-2" width="32" height="32"><p>32px</p></div><div><img src="http://127.0.0.1:8789/favicon.svg?v=ha-2" width="64" height="64"><p>64px</p></div></body>');
await preview.evaluate(()=>Promise.all([...document.images].map(img=>img.decode())));
await preview.screenshot({path:'output/playwright/favicon-ha-preview.png'});
await preview.close();
return {report,trace};
}
